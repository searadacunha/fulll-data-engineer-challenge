def session():
    """Run main() with scripted answers, echoing each one as a terminal would."""
    answers = iter(SESSION)
    output = io.StringIO()

    def fake_input(prompt=""):
        answer = next(answers)
        print(f"{prompt}{answer}", file=output)
        return answer

    with mock.patch.object(builtins, "input", fake_input), contextlib.redirect_stdout(output):
        bi.main()
    return "```text\n" + output.getvalue().rstrip() + "\n```\n"


