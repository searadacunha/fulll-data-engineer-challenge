def n(value):
    return f"{value:,}"


def seconds(value, decimals=0):
    return f"{value:,.{decimals}f} s ({timedelta(seconds=round(value))})"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def by_city(label, values):
    """One table row: a label, then one cell per city."""
    return [label, *(values[city] for city in bi.CITY_DATA)]


