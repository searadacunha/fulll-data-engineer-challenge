def compute(df):
    with contextlib.redirect_stdout(io.StringIO()):
        return {
            "time": bi.time_stats(df),
            "station": bi.station_stats(df),
            "duration": bi.trip_duration_stats(df),
            "user": bi.user_stats(df),
        }


def with_counts(values, counts, label=str):
    if not values:
        return "no data"
    cells = [f"{label(value)} ({n(int(counts[value]))})" for value in values]
    return ", ".join(cells) + (" (tie)" if len(values) > 1 else "")


def city_results(city):
    df = bi.load_data(city, "all", "all")
    r = compute(df)
    start = df["Start Time"]
    trips = df.groupby(["Start Station", "End Station"], observed=True).size()
    months = start.dt.month.value_counts()
    days = start.dt.day_of_week.value_counts()
    hours = start.dt.hour.value_counts()
    month_number = {name: i + 1 for i, name in enumerate(bi.MONTH_NAMES)}
    cells = {
        "Trips": n(len(df)),
        "Most common month": with_counts(
            [month_number[m] for m in r["time"]["mostCommonMonth"]],
            months,
            lambda m: bi.MONTH_NAMES[m - 1].title(),
        ),
        "Most common day of week": with_counts(
            [bi.DAYS.index(d) for d in r["time"]["mostCommonDayOfWeek"]],
            days,
            lambda d: bi.DAYS[d].title(),
        ),
        "Most common start hour": with_counts(
            r["time"]["mostCommonStartHour"], hours, lambda h: f"{h:02d}:00"
        ),
        "Most common start station": with_counts(
            r["station"]["mostCommonStartStation"], df["Start Station"].value_counts()
        ),
        "Most common end station": with_counts(
            r["station"]["mostCommonEndStation"], df["End Station"].value_counts()
        ),
        "Most common trip": with_counts(
            r["station"]["mostCommonTrip"], trips, lambda trip: f"{trip[0]} to {trip[1]}"
        ),
        "Total travel time": seconds(r["duration"]["totalTravelTime"]),
        "Mean travel time": seconds(r["duration"]["meanTravelTime"], decimals=1),
        "User types": counts_text(r["user"]["userTypeCounts"]),
        "Gender": "not in the file"
        if r["user"]["genderCounts"] is None
        else counts_text(r["user"]["genderCounts"])
        + f" ({n(int(df['Gender'].isna().sum()))} not recorded)",
        "Earliest, most recent year of birth": "not in the file"
        if r["user"]["earliestBirthYear"] is None
        else f"{r['user']['earliestBirthYear']}, {r['user']['mostRecentBirthYear']}",
        "Most common year of birth": "not in the file"
        if "Birth Year" not in df.columns
        else with_counts(
            r["user"]["mostCommonBirthYear"],
            df["Birth Year"].value_counts().rename(index=int),
        ),
    }

    durations = df["Trip Duration"]
    dedup = df.drop_duplicates()
    r_dedup = compute(dedup)
    changed = [
        key for part in ("time", "station") for key in r[part] if r[part][key] != r_dedup[part][key]
    ]
    if r["user"]["mostCommonBirthYear"] != r_dedup["user"]["mostCommonBirthYear"]:
        changed.append("mostCommonBirthYear")
    early = df[start.dt.month <= 3]
    context = {
        "mean_within_day": seconds(durations[durations <= 86400].mean(), decimals=1),
        "duplicates": len(df) - len(dedup),
        "dedup_changed": changed,
        "dedup_total": r["duration"]["totalTravelTime"] - r_dedup["duration"]["totalTravelTime"],
        "early_hour": with_counts(
            compute(early)["time"]["mostCommonStartHour"],
            early["Start Time"].dt.hour.value_counts(),
            lambda h: f"{h:02d}:00",
        ),
        "months": months,
        "days": days,
    }
    return cells, context


def results_table(results):
    cities = list(bi.CITY_DATA)
    rows = [[label, *(results[c][0][label] for c in cities)] for label in results["chicago"][0]]
    return table(["", *(TITLES[c] for c in cities)], rows)


