def inspect(city):
    """Facts about one raw file, read as text so that nothing is cleaned beforehand."""
    path = DATA / bi.CITY_DATA[city]
    raw = pd.read_csv(path, dtype=str, keep_default_na=False)
    first = raw.columns[0]
    ids = pd.to_numeric(raw[first], errors="coerce")
    start = pd.to_datetime(raw["Start Time"], format=bi.TIME_FORMATS[0], errors="coerce")
    end = pd.to_datetime(raw["End Time"], format=bi.TIME_FORMATS[0], errors="coerce")
    duration = pd.to_numeric(raw["Trip Duration"], errors="coerce")
    gap = (duration - (end - start).dt.total_seconds()).abs()
    names = pd.concat([raw["Start Station"], raw["End Station"]]).unique()
    early = start.dt.month <= 3

    def near(target):
        return int(((gap - target).abs() <= 60).sum())

    facts = {
        "bytes": path.stat().st_size,
        "sha": fetch_data.sha256(path.read_bytes()),
        "rows": len(raw),
        "columns": list(raw.columns[1:]),
        "first": first,
        "ids_ok": bool(ids.notna().all() and ids.is_unique and (ids % 1 == 0).all()),
        "duplicates": int(raw.drop(columns=first).duplicated().sum()),
        "empty": {column: int((raw[column] == "").sum()) for column in raw.columns[1:]},
        "iso": int(raw["Start Time"].str.fullmatch(ISO).sum())
        + int(raw["End Time"].str.fullmatch(ISO).sum()),
        "unparsed": int(start.isna().sum() + end.isna().sum()),
        "first_start": start.min(),
        "last_start": start.max(),
        "ends_in_july": int((end >= pd.Timestamp(2017, 7, 1)).sum()),
        "whole_seconds": bool(raw["Trip Duration"].str.fullmatch(r"\d+").all()),
        "duration": duration,
        "gap": {
            "within 1 s": int((gap <= 1).sum()),
            "1 s to 1 min": int(((gap > 1) & (gap <= 60)).sum()),
            "about 1 h": near(3600),
            "about 12 h": near(43200),
            "about 24 h": near(86400),
        },
        "end_before_start": int((end < start).sum()),
        # Trips one hour apart that span 2:00 on 12 March 2017, when US clocks moved forward.
        "across_clock_change": int(
            (
                ((gap - 3600).abs() <= 60)
                & (start < pd.Timestamp(2017, 3, 12, 2))
                & (end >= pd.Timestamp(2017, 3, 12, 2))
            ).sum()
        ),
        "start_stations": raw["Start Station"].nunique(),
        "end_stations": raw["End Station"].nunique(),
        "outer_spaces": sum(name != name.strip() for name in names),
        "inner_spaces": sum("  " in name.strip() for name in names),
        "merged": len(names) - len({" ".join(name.split()) for name in names}),
        "round_trips": int((raw["Start Station"] == raw["End Station"]).sum()),
        "user_types": raw["User Type"].value_counts().to_dict(),
        "hours_early": sorted(start[early].dt.hour.unique().tolist()),
        "hours_late": sorted(start[~early].dt.hour.unique().tolist()),
        "whole_minutes_early": float((start[early].dt.second == 0).mean()),
        "whole_minutes_late": float((start[~early].dt.second == 0).mean()),
    }
    facts["gap"]["other"] = facts["rows"] - sum(facts["gap"].values())
    if "Gender" in raw.columns:
        facts["genders"] = raw["Gender"].value_counts().to_dict()
        text = raw["Birth Year"]
        years = pd.to_numeric(text[text != ""], errors="coerce")
        facts["birth"] = {
            "decimal_text": bool(text[text != ""].str.fullmatch(r"\d{4}\.0").all()),
            "not_whole": int((years % 1 != 0).sum()),
            "min": int(years.min()),
            "max": int(years.max()),
            "over_100": int((years < 1917).sum()),
            "lowest": years.value_counts().sort_index().head(5),
            "highest": years.value_counts().sort_index().tail(5),
        }
    return facts


def counts_text(counts):
    shown = {("(empty)" if key == "" else key): value for key, value in counts.items()}
    return ", ".join(f"{key} {n(value)}" for key, value in shown.items())


def clock_change_note(f):
    """Explain the trips whose duration and timestamps are one hour apart, if all are explained."""
    hour = {c: f[c]["gap"]["about 1 h"] for c in bi.CITY_DATA if f[c]["gap"]["about 1 h"]}
    if any(f[c]["across_clock_change"] != count for c, count in hour.items()):
        return "- Some trips one hour apart do not span the clock change of 12 March 2017."
    where = " and ".join(f"{TITLES[c]} {n(count)}" for c, count in hour.items())
    return (
        f"- Trips one hour apart ({where}): all of them span 2:00 on 12 March 2017, when "
        "clocks moved forward an hour. The duration is right; the timestamps are local times."
    )


def over_day_share(durations):
    """Share of the total recorded time that comes from trips longer than 24 hours."""
    return durations[durations > 86400].sum() / durations.sum()


def years_text(counts):
    return ", ".join(f"{int(year)} ({n(count)})" for year, count in counts.items())


